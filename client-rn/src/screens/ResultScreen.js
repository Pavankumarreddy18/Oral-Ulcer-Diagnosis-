import React, { useState, useEffect } from 'react';
import { View, Text, TouchableOpacity, StyleSheet, ScrollView, ActivityIndicator, Alert, Platform, Share } from 'react-native';
import { useSafeAreaInsets } from 'react-native-safe-area-context';
import { LinearGradient } from 'expo-linear-gradient';
import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import AsyncStorage from '@react-native-async-storage/async-storage';
import { ThemeContext } from '../context/ThemeContext';

export default function ResultScreen({ route, navigation }) {
  const { colors, isDark, fs } = React.useContext(ThemeContext);
  const { resultText, formData } = route.params || {};
  const isDual = typeof resultText === 'object' && resultText !== null;
  const primaryResult = isDual ? resultText.primary : resultText;
  const imageResult = isDual ? resultText.image : null;
  
  const [user, setUser] = useState(null);
  const [pdfLoading, setPdfLoading] = useState(false);
  const insets = useSafeAreaInsets();

  useEffect(() => {
    AsyncStorage.getItem('user').then(data => {
      if (data) setUser(JSON.parse(data));
    });
  }, []);

  const generatePDFUri = async () => {
    const dateStr = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
    const patientName = formData?.name || user?.name || user?.email || "Patient";
    
    const htmlContent = `
      <html>
        <head>
          <style>
            body { font-family: Helvetica, sans-serif; padding: 20px; color: #333; }
            h1 { color: #4f46e5; border-bottom: 2px solid #4f46e5; padding-bottom: 10px; }
            .box { background: #f8fafc; padding: 15px; border-radius: 8px; margin-bottom: 20px; }
            .result { line-height: 1.6; white-space: pre-wrap; }
            .footer { margin-top: 40px; font-size: 12px; color: #666; border-top: 1px solid #ccc; padding-top: 10px; }
          </style>
        </head>
        <body>
          <h1>OUDS Clinical Diagnostic Report</h1>
          <div class="box">
            <p><strong>Patient Name:</strong> ${patientName}</p>
            <p><strong>Date:</strong> ${dateStr}</p>
          </div>
          <h2>Primary Analysis (Symptoms)</h2>
          <div class="result">${(primaryResult || "No diagnostic findings.").replace(/\n/g, '<br>')}</div>
          ${imageResult ? `
            <h2>Image-Driven Analysis</h2>
            <div class="result">${imageResult.replace(/\n/g, '<br>')}</div>
          ` : ''}
          <div class="footer">
            DISCLAIMER: This report is generated by an AI screening model for informational purposes only.
            It does not replace professional clinical evaluation. Consult a licensed Dentist or Oral Surgeon for definitive diagnosis.
          </div>
        </body>
      </html>
    `;

    const { uri } = await Print.printToFileAsync({ html: htmlContent });
    return uri;
  };

  const handleDownloadPDF = async () => {
    setPdfLoading(true);
    try {
      const uri = await generatePDFUri();
      if (await Sharing.isAvailableAsync()) {
        await Sharing.shareAsync(uri, { UTI: '.pdf', mimeType: 'application/pdf', dialogTitle: 'Download PDF' });
      } else {
        Alert.alert('PDF Generated', `Saved to ${uri}`);
      }
    } catch (err) {
      Alert.alert('Error', 'Failed to generate PDF');
    } finally {
      setPdfLoading(false);
    }
  };

  const handleSharePDF = async () => {
    setPdfLoading(true);
    try {
      const uri = await generatePDFUri();
      if (await Sharing.isAvailableAsync()) {
        await Sharing.shareAsync(uri, { UTI: '.pdf', mimeType: 'application/pdf', dialogTitle: 'Share PDF' });
      }
    } catch (err) {
      Alert.alert('Error', 'Failed to share diagnosis');
    } finally {
      setPdfLoading(false);
    }
  };

  // Helper to nicely format the text on screen
  const formatText = (text) => {
    if (!text) return <Text style={[styles.bodyText, { color: colors.textPrimary, fontSize: fs(15) }]}>No diagnostic findings.</Text>;
    const cleanText = text.replace(/\*\*/g, '');
    const lines = cleanText.split('\n').filter(l => l.trim() !== '');
    
    return lines.map((line, idx) => {
      if (line.match(/^([-*•]\s*)?(\d+\.\s*)?(MOST LIKELY DIAGNOSIS|DIFFERENTIAL DIAGNOSES|ULCER CATEGORY|RISK LEVEL|URGENCY|KEY FINDINGS|RED FLAGS|RECOMMENDED ACTION|RECOMMENDED ACTIONS|DISCLAIMER)[:\s*-]*/i)) {
        return <Text key={idx} style={[styles.headingText, { fontSize: fs(16) }]}>{line.replace(/^[#*•\-\s]+/, '').trim()}</Text>;
      }
      return <Text key={idx} style={[styles.bodyText, { color: colors.textPrimary, fontSize: fs(15) }]}>• {line.replace(/^[-*•]\s*/, '')}</Text>;
    });
  };

  return (
    <View style={[styles.container, { backgroundColor: colors.background }]}>
      <LinearGradient 
        colors={['#4f46e5', '#a855f7']} 
        start={{x: 0, y: 0}} end={{x: 1, y: 1}}
        style={[styles.headerGradient, { paddingTop: Math.max(insets.top, 20) + 16 }]}
      >
        <Text style={[styles.title, { fontSize: fs(28) }]}>Diagnosis Report</Text>
        <Text style={[styles.subtitle, { fontSize: fs(15) }]}>AI-Powered Clinical Screening</Text>
      </LinearGradient>

      <ScrollView contentContainerStyle={[styles.content, { paddingBottom: insets.bottom + 24 }]}>
        <View style={[styles.card, { backgroundColor: colors.card, borderColor: colors.border }]}>
          <View style={[styles.cardHeader, { borderBottomColor: colors.border }]}>
            <Text style={[styles.cardTitle, { color: colors.textPrimary, fontSize: fs(18) }]}>🤖 Primary Analysis (Symptoms)</Text>
          </View>
          {formatText(primaryResult)}
        </View>

        <View style={[styles.card, { backgroundColor: colors.card, borderColor: colors.border }]}>
          <View style={[styles.cardHeader, { borderBottomColor: colors.border }]}>
            <Text style={[styles.cardTitle, { color: colors.textPrimary, fontSize: fs(18) }]}>📷 Image-Driven Analysis</Text>
          </View>
          {imageResult ? (
             formatText(imageResult)
          ) : (
             <View style={{ paddingVertical: 32, alignItems: 'center' }}>
               <Text style={{ fontSize: 40, marginBottom: 12 }}>🖼️</Text>
               <Text style={{ fontSize: fs(16), fontWeight: '700', color: colors.textPrimary }}>No photo uploaded</Text>
               <Text style={{ fontSize: fs(14), color: colors.textSecondary, marginTop: 4 }}>Image parameter analysis is unavailable.</Text>
             </View>
          )}
        </View>

        <TouchableOpacity onPress={handleDownloadPDF} disabled={pdfLoading}>
          <LinearGradient 
            colors={['#0ea5e9', '#3b82f6']} 
            start={{x: 0, y: 0}} end={{x: 1, y: 0}} 
            style={styles.pdfButton}
          >
            {pdfLoading ? <ActivityIndicator color="#fff" /> : (
              <Text style={[styles.pdfButtonText, { fontSize: fs(16) }]}>⬇️ Download PDF</Text>
            )}
          </LinearGradient>
        </TouchableOpacity>
        
        <TouchableOpacity onPress={handleSharePDF} disabled={pdfLoading} style={{ marginBottom: 16 }}>
          <LinearGradient 
            colors={['#10b981', '#059669']} 
            start={{x: 0, y: 0}} end={{x: 1, y: 0}} 
            style={styles.pdfButton}
          >
            {pdfLoading ? <ActivityIndicator color="#fff" /> : (
              <Text style={[styles.pdfButtonText, { fontSize: fs(16) }]}>📤 Share PDF</Text>
            )}
          </LinearGradient>
        </TouchableOpacity>

        <TouchableOpacity style={[styles.secondaryButton, isDark && styles.secondaryButtonDark]} onPress={() => navigation.popToTop()}>
          <Text style={[styles.secondaryButtonText, isDark && styles.secondaryButtonTextDark, { fontSize: fs(16) }]}>Return to Dashboard</Text>
        </TouchableOpacity>
      </ScrollView>
    </View>
  );
}

